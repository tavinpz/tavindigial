import { iniciar } from './lib.mjs'
import fs from 'fs'
const base = fs.readFileSync('dados_msg.js', 'utf8')
const a = await iniciar()
await a.preparar(new Function(base))
await a.abrir('/mensagens')
await a.clicar('Mariana Costa'); await a.espera(1200)
const ultimoBotao = (t) => a.p.evaluateHandle((t) => { const vis = [...document.querySelectorAll('button')].filter((b) => b.getBoundingClientRect().width > 0); if (t === 'Pausar IA') { const p = vis.find((b) => (b.title || '').startsWith('Pausar a IA') || (b.title || '').startsWith('IA pausada')); const m = vis.filter((b) => b.innerText.trim() === 'Pausar IA').pop(); return m || p } return vis.filter((b) => b.innerText.trim().startsWith(t)).pop() }, t)
await a.foto('g1_conversa', { pausar: await ultimoBotao('Pausar IA'), mariana: 'Mariana Costa' })
await (await ultimoBotao('Pausar IA')).evaluate((b) => b.click()); await a.espera(900)
await a.foto('g2_modal', { amanha: 'Amanhã às 08:00' })
await a.clicar('Amanhã às 08:00'); await a.espera(500)
await a.foto('g3_escolhido', { confirma: await ultimoBotao('Pausar IA') })
await (await ultimoBotao('Pausar IA')).evaluate((b) => b.click()); await a.espera(1000)
await a.foto('g4_pausada', { faixa: 'IA pausada — as respostas', campo: 'Digite sua mensagem...' })
await a.digitar('Digite sua mensagem...', 'Pode sim! Reservo as duas às 9h, uma depois da outra 😊')
await a.foto('g5_digitado', { enviar: await ultimoBotao('Enviar') })
await a.fim('msg')

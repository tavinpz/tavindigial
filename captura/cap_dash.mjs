import { iniciar } from './lib.mjs'
import fs from 'fs'
const a = await iniciar()
await a.preparar(new Function(fs.readFileSync('dados_dash.js', 'utf8')))
await a.abrir('/dashboard', 'base', 1440, 1000)
await a.espera(1500)
const bt = (t) => a.p.evaluateHandle((t) => [...document.querySelectorAll('button')].find((b) => b.innerText.trim() === t), t)
await a.foto('y0_hoje', { p30: await bt('30d') })
await (await bt('30d')).evaluate((b) => b.click()); await a.espera(1500)
await a.foto('y1_30d', { kpis: 'ATENDIMENTOS DA THATA', receita: 'RECEITA ESTIMADA', conv: 'CONVERSÃO DA THATA', semanas: await bt('Semanas') })
await (await bt('Semanas')).evaluate((b) => b.click()); await a.espera(1500)
await a.foto('y2_semanas', {})
await a.p.evaluate(() => { const el = [...document.querySelectorAll('*')].filter((e) => e.scrollHeight > e.clientHeight + 100 && /auto|scroll/.test(getComputedStyle(e).overflowY)).sort((x, y) => y.scrollHeight - x.scrollHeight)[0]; (el || document.scrollingElement).scrollTop = 560 }); await a.espera(900)
await a.foto('y3_padroes', { melhor: 'MELHOR HORÁRIO', ultimos: 'ÚLTIMOS AGENDAMENTOS' })
await a.fim('dash')

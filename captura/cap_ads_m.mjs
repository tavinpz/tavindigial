import { iniciar } from './lib.mjs'
import fs from 'fs'
const a = await iniciar()
await a.preparar(new Function(fs.readFileSync('dados_ads.js', 'utf8')))
await a.abrir('/integracoes')
await a.p.evaluate(() => { const el = [...document.querySelectorAll('*')].find((e) => (e.innerText || '').trim() === 'Lead entrou pelo anúncio'); el.scrollIntoView({ block: 'center' }) }); await a.espera(800)
await a.foto('v1_meta', { card: 'Meta Ads', eventos: 'Lead entrou pelo anúncio' })
await a.abrir('/mensagens')
const chip = () => a.p.evaluateHandle(() => { const b = [...document.querySelectorAll('button')]; const i = b.findIndex((x) => x.innerText.trim() === 'Esperando +24h'); return b[i + 1] })
await a.foto('v2_lista', { chip: await chip(), selo: await a.p.evaluateHandle(() => [...document.querySelectorAll('*')].filter((e) => e.getAttribute && /anúncio/i.test(e.getAttribute('title') || '')).shift()) })
await (await chip()).evaluate((b) => b.click()); await a.espera(800)
await a.foto('v3_menu', { op: 'Clareamento | Novembro' }); await a.botoes()
const b = await iniciar()
await b.preparar(new Function('window.__soAds = true;\n' + fs.readFileSync('dados_ads.js', 'utf8')))
await b.abrir('/mensagens')
await b.p.evaluate(() => { const bs = [...document.querySelectorAll('button')]; const i = bs.findIndex((x) => x.innerText.trim() === 'Esperando +24h'); bs[i + 1].click() }); await b.espera(700)
await b.clicar('Clareamento | Novembro'); await b.espera(1200)
await b.foto('v4_filtrado', { mariana: 'Mariana Costa' })
await b.fim('ads2')
await a.clicar('Clareamento | Novembro'); await a.espera(1200)
await a.clicar('Mariana Costa'); await a.espera(1200)
await a.p.evaluate(() => [...document.querySelectorAll('button')].find((b) => (b.title || '').startsWith('Ver informa')).click()); await a.espera(1500)
await a.foto('v5_ficha', { aba: 'Anúncio' }); await a.botoes()
await a.p.evaluate(() => [...document.querySelectorAll('button')].filter((b) => b.innerText.trim().startsWith('Anúncio')).pop().click()); await a.espera(1200)
await a.foto('v6_anuncio', {})
await a.fim('ads')

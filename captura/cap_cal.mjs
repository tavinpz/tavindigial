import { iniciar } from './lib.mjs'
import fs from 'fs'
const base = fs.readFileSync('dados_cal.js', 'utf8')
const a = await iniciar()
await a.preparar(new Function(base))
await a.abrir('/calendario')
const lockBtn = () => a.p.evaluateHandle(() => { const b = [...document.querySelectorAll('button')]; const i = b.findIndex((x) => x.innerText.trim() === 'Mês'); return b[i + 1] })
await a.foto('d1_mes', { proximos: 'PRÓXIMOS EVENTOS', editar: 'Editar', lock: await lockBtn() })
await a.clicar('Editar'); await a.espera(1200)
await a.foto('d2_editar', { seg: 'Segunda', aplicar: 'Aplicar horário de segunda' })
await a.clicar('Cancelar'); await a.espera(600)
await (await lockBtn()).evaluate((b) => b.click()); await a.espera(900)
await a.p.evaluate(() => { const d = new Date(); d.setDate(d.getDate() + 10); const v = d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0'); const i = document.querySelector('input[type=date]'); const set = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set; set.call(i, v); i.dispatchEvent(new Event('input', { bubbles: true })); i.dispatchEvent(new Event('change', { bubbles: true })) }); await a.espera(500)
await a.foto('d3_travar', { data: await a.p.evaluateHandle(() => document.querySelector('input[type=date]')), congresso: 'Congresso' })
await a.clicar('Congresso'); await a.espera(500)
await a.foto('d3b_motivo', { travar: 'Travar o dia' })
await a.fim('cal')
const b = await iniciar()
await b.preparar(new Function('window.__trava = true;\n' + base))
await b.abrir('/calendario')
await b.foto('d4_travado', { card: 'DIAS TRAVADOS', dia: await b.p.evaluateHandle(() => [...document.querySelectorAll('*')].filter((e) => /trava/i.test(e.innerText || '') && e.children.length === 0 && e.getBoundingClientRect().x < 1200 && e.getBoundingClientRect().x > 300)[0]) })
await b.fim('cal2')
